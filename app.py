def is_valid_email(email: str) -> bool:
    """Validates clinical email addresses before attempting SMTP dispatch."""
    pattern = r'^[\w\.-]+@[\w\.-]+\.\w+$'
    return re.match(pattern, email) is not None

def send_secure_email(recipient_email: str, pdf_bytes: bytes, filename: str, accession_id: str):
    """Packages the clinical PDF report and transmits it securely via SMTP."""
    try:
        sender_email = st.secrets["EMAIL_SENDER"]
        sender_password = st.secrets["EMAIL_PASSWORD"]
    except KeyError:
        return False, "SMTP credentials missing. Please configure .streamlit/secrets.toml."
        
    msg = MIMEMultipart()
    msg['From'] = sender_email
    msg['To'] = recipient_email
    msg['Subject'] = f"[CONFIDENTIAL] DermaTrust AI Triage Report - Accession: {accession_id}"
    
    body = f"""
    CONFIDENTIAL MEDICAL RECORD
    
    Please find attached the automated clinical triage report for scan accession {accession_id}.
    
    This report was generated by the DermaTrust AI Clinical Decision Support System. 
    Note: This is an investigational CDSS tool. Automated triage routing must be verified by an attending physician prior to clinical intervention.
    
    Do not reply to this automated dispatch.
    
    Regards,
    DermaTrust AI Diagnostics Engine
    """
    msg.attach(MIMEText(body, 'plain'))
    
    # Attach PDF Payload
    part = MIMEApplication(pdf_bytes, Name=filename)
    part['Content-Disposition'] = f'attachment; filename="{filename}"'
    msg.attach(part)
    
    try:
        # Defaulting to Gmail SMTP (port 587 for TLS)
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(sender_email, sender_password)
        server.send_message(msg)
        server.quit()
        return True, "Payload dispatched successfully."
    except Exception as e:
        return False, f"SMTP Protocol Error: {str(e)}"

